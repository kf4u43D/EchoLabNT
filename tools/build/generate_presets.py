#!/usr/bin/env python3
"""Generate the host profiles and NT factory table from the musical preset bank."""
import argparse
from decimal import Decimal, ROUND_HALF_UP
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
NOTES = ('1/1','1/2','1/4','1/8','1/16','1/4D','1/8D','1/4T','1/8T','1/16T')
MODELS = ('digital','analog','tube','pingpong','multihead','8bit','dynamic','tape','sweep','analogmod',
          'digitalmod','reverse','autovolume','digitalrack','platter','stereo','looper','exciter','sweepup','tubea04')
VOICES = {'auto':0,'a04':1,'a05':2,'b06':3}
LOOPS = {'stop':0,'record':1,'play':2,'overdub':3,'clear':4}
FIELDS = (
    ('Feedback','feedback',1000),('Mix','mix',1000),('Tone','tone_hz',1),('Drive','drive',1000),
    ('BitDepth','bit_depth',1),('ModRate','mod_rate_hz',100),('ModDepth','mod_depth_ms',100),
    ('DuckThreshold','duck_threshold_db',10),('DuckAmount','duck_amount',1000),('Attack','attack_ms',1),
    ('Release','release_ms',1),('Swell','swell_ms',1),('StereoRatio','stereo_ratio',100),
    ('LimiterOn','limiter_enabled',1),('LimiterCeiling','limiter_ceiling',1000),('LimiterReleaseMs','limiter_release_ms',1),
    ('SampleRateHz','sample_rate_hz',1),('ExciterAmount','exciter_amount',1000),('ExciterTuneHz','exciter_tune_hz',1),
    ('TapPattern','tap_pattern',1),('Mod1Source','mod1_source',1),('Mod1Destination','mod1_destination',1),
    ('Mod1Amount','mod1_amount',1000),('Mod2Source','mod2_source',1),('Mod2Destination','mod2_destination',1),
    ('Mod2Amount','mod2_amount',1000),('FeedbackLPHz','feedback_lowpass_hz',1),('Drift','drift_amount',1000),
    ('FeedbackHPHz','feedback_highpass_hz',1),('LoResEndHz','lores_rate_end_hz',1),('LoResDecayMs','lores_rate_decay_ms',1),
    ('LoResEnvelopeAmount','lores_rate_envelope_amount',1000),('RackSampleRateHz','digital_rack_rate_hz',1),
    ('LoResCutoffHz','lores_cutoff_hz',1),('ModulationEnabled','modulation_enabled',1),
    ('ExciterHighpassOn','exciter_highpass_enabled',1),('WetToneOn','wet_tone_enabled',1),
    ('StereoTiming','stereo_timing_enabled',1),
)


def nt_number(value, scale=1):
    result=int((Decimal(str(int(value) if isinstance(value,bool) else value))*scale).quantize(Decimal(1),rounding=ROUND_HALF_UP))
    if not -32768 <= result <= 32767:
        raise ValueError('NT value does not fit int16: '+str(value))
    return result


def bank_outputs(root=ROOT):
    bank=json.loads((root/'models/preset_bank.json').read_text(encoding='utf-8'))
    defaults=bank['defaults']
    expected={key for _,key,_ in FIELDS}|{'model','sync_mode','tempo_bpm','division','right_division','loop_action','voicing'}
    if set(defaults)!=expected or 'delay_ms' in defaults:
        raise ValueError('Bank defaults must specify every supported sound field and musical timing only')
    presets=bank['presets']
    slot_count=bank['slot_count']
    retired=bank['retired_slots']
    slots=[preset['slot'] for preset in presets]
    if not presets or len({p['id'] for p in presets})!=len(presets) or len({p['name'] for p in presets})!=len(presets):
        raise ValueError('The factory bank requires unique recipe IDs and names')
    if not isinstance(slot_count,int) or slot_count<1 or any(not isinstance(slot,int) for slot in slots+retired):
        raise ValueError('Factory slots must be positive integers')
    if len(set(slots+retired))!=slot_count or sorted(slots+retired)!=list(range(1,slot_count+1)):
        raise ValueError('Every permanent factory slot must be active or retired, without reuse or gaps')
    presets=sorted(presets,key=lambda preset:preset['slot'])
    by_slot={preset['slot']:preset for preset in presets}
    default_id=bank.get('default_preset')
    default_preset=next((preset for preset in presets if preset['id']==default_id),None)
    if not isinstance(default_id,str) or default_preset is None:
        raise ValueError('The NT default_preset must identify an active factory recipe')
    profiles={}
    lines=['#pragma once','// Generated by tools/build/generate_presets.py from models/preset_bank.json.',
           '// Included inside echolab_nt after the published parameter enum.','namespace preset_bank {',
           'struct Value { int parameter; std::int16_t value; };',
           'struct Preset { const char* name; const Value* values; unsigned count; };',
           f'inline constexpr unsigned count={len(presets)};',
           f'inline constexpr unsigned slotCount={slot_count};',
           f'inline constexpr unsigned defaultSlot={default_preset["slot"]};']
    for preset in presets:
        index=preset['slot']-1
        key=preset['id']
        if not key or any(c not in 'abcdefghijklmnopqrstuvwxyz0123456789_' for c in key):
            raise ValueError('Invalid preset identifier: '+key)
        if not set(preset['parameters'])<=expected:
            raise ValueError('Unknown preset parameters: '+key)
        p={**defaults,**preset['parameters']}
        if p['sync_mode']!='internal' or p['division'] not in NOTES or p['right_division'] not in ('ratio',*NOTES):
            raise ValueError('Factory recipes require internal note divisions: '+key)
        values=[('Model',MODELS.index(p['model'])),('Bypass',0)]
        values.extend((parameter,nt_number(p[field],scale)) for parameter,field,scale in FIELDS)
        values.extend((('LoopAction',LOOPS[p['loop_action']]),('ClockPpqn',2),('SyncMode',3),
                       ('TempoBpm',nt_number(p['tempo_bpm'])),('Division',NOTES.index(p['division'])),
                       ('RightDivision',0 if p['right_division']=='ratio' else NOTES.index(p['right_division'])+1),
                       ('Voicing',VOICES[p['voicing']]),('Version',1 if p['voicing']=='b06' else 0)))
        lines.append(f'inline constexpr Value p{index}[]={{')
        lines.extend('    {'+parameter+','+str(value)+'},' for parameter,value in values)
        lines.append('};')
        profile=['# '+preset['name'],'# '+preset['purpose'],'# '+preset['technique']]
        profile.extend(field+'='+str(int(value) if isinstance(value,bool) else value) for field,value in p.items())
        profiles[root/'models/presets'/f'{key}.profile']='\n'.join(profile)+'\n'
    lines.append('inline constexpr Preset presets[slotCount]={')
    for slot in range(1,slot_count+1):
        if slot in by_slot:
            preset=by_slot[slot]
            index=slot-1
            lines.append('    {'+json.dumps(preset['name'])+f',p{index},static_cast<unsigned>(sizeof(p{index})/sizeof(p{index}[0]))'+'},')
        else:
            lines.append('    {"Custom",nullptr,0},')
    lines.append('};')
    lines.extend((
        'constexpr std::int16_t defaultValue(int parameter,std::int16_t fallback) noexcept {',
        '    const auto& preset=presets[defaultSlot-1];',
        '    for(unsigned i=0;i<preset.count;++i)',
        '        if(preset.values[i].parameter==parameter) return preset.values[i].value;',
        '    return fallback;',
        '}',
    ))
    lines.append('inline constexpr const char* const names[slotCount+1]={"Custom",')
    lines.extend('    '+json.dumps(by_slot[slot]['name'] if slot in by_slot else 'Custom')+',' for slot in range(1,slot_count+1))
    lines.append('};')
    lines.append('inline constexpr unsigned activeSlots[count]={'+','.join(str(preset['slot']) for preset in presets)+'};')
    lines.extend(('} // namespace preset_bank',''))
    return {**profiles,root/'src/nt/factory_presets.h':'\n'.join(lines)}


def stale_outputs(outputs, root=ROOT):
    stale=[path.relative_to(root).as_posix() for path,text in outputs.items()
           if not path.is_file() or path.read_text(encoding='utf-8')!=text]
    extras=set((root/'models/presets').glob('*.profile'))-set(outputs)
    return stale+sorted(path.relative_to(root).as_posix() for path in extras)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true',help='Fail if generated files are stale; do not write')
    args=parser.parse_args()
    try:
        outputs=bank_outputs()
        extras=set((ROOT/'models/presets').glob('*.profile'))-set(outputs)
        if args.check:
            stale=stale_outputs(outputs)
            if stale:
                print('Stale preset outputs: '+', '.join(stale),file=sys.stderr)
                return 1
            print(f'Factory bank verified: {len(outputs)-1} musical profiles and NT table')
            return 0
        if extras:
            raise ValueError('Unexpected profiles; preserve and remove them explicitly before generation: '+', '.join(p.name for p in sorted(extras)))
        for path,text in outputs.items():
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(text,encoding='utf-8',newline='\n')
        print(f'Generated {len(outputs)-1} musical profiles and NT factory table')
        return 0
    except (OSError,ValueError,KeyError,TypeError) as error:
        print('Preset generation failed: '+str(error),file=sys.stderr)
        return 1


if __name__=='__main__':
    sys.exit(main())
